#' @include RSScalar.r
#' @title RSBoolean: Logical Scalar Wrapper
#'
#' @description
#' `RSBoolean` wraps a logical (TRUE/FALSE) scalar. It inherits from `RSScalar` and
#' provides boolean-specific behavior, including conversion to numeric via `asNumber()`.
#' `RSBoolean$new(NA)` returns the shared `RSNABoolean` instance.
#' 
#' @section Protocols:
#' - [RSComparable]
#' - [RSCoding]
#' - [RSCopying]
#'
#' @section Methods:
#' - `asNumber()` — Returns an `RSNumber` with value 1L or 0L, or
#'   `RSNumber$na` for a missing boolean.
#' 
#' @section Usage:
#' To create an instance, use the static constructor:
#' \code{RSBoolean_withBoolean(val)}, which returns \code{RSNABoolean} if \code{val} is \code{NA}.
#' 
#' @examples
#' flag <- RSBoolean_withBoolean(TRUE)
#' flag$value()
#' flag$asNumber()$value()
#' identical(RSBoolean_withBoolean(NA), RSBoolean$na)
#'
#' @export
RSBoolean <- RSScalarClass(
  "RSBoolean",
  version     = "0.2.0",
  super_class = RSScalar,
  na_value    = NA,
  public      = list(

    #' @description
    #' Initializes an `RSBoolean` object by wrapping a logical scalar.
    #' This constructor verifies that the input is of class `logical`, and stores
    #' it as the internal value. Only scalar (length 1) logical values are supported.
    #' @param val A logical scalar without an S3 class attribute.
    #' @return The initialized `RSBoolean` object (invisible).
    initialize = function(val) {
      if (!inherits(val, "logical")) stop("`val` must be of class logical")
      if (is.object(val))
        stop("S3 class attributes are not supported for RSBoolean.", call. = FALSE)
      super$initialize(val)
    },



    #' @description
    #' Returns an integer representation of the boolean value.
    #' Converts the internal logical value (`TRUE` or `FALSE`) to an `RSNumber`
    #' object (`1L` or `0L`, respectively). Missing values become `RSNumber$na`.
    #' @return An `RSNumber` with value `1L` or `0L`, or the shared `RSNumber$na`.
    asNumber = function() RSNumber_withValue(as.integer(private$.val))

  )
)



#' @title RSNABoolean
#' @description Logical NA companion for RSBoolean. Generated by [RSScalarClass()] when
#'   `RSBoolean` is declared. Use `RSBoolean$na` for the shared instance.
#' @section Protocols:
#' - [RSComparable]
#' - [RSCoding]
#' - [RSCopying]
#'
#' @examples
#' missing_flag <- RSBoolean$na
#' missing_flag$isMemberOf(RSNABoolean)
#' is.na(missing_flag$value())
#'
#' @return The NA class generator.
#' @export
RSNABoolean <- RSBoolean$na$class()
